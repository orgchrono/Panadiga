//! C11 header (`digaos_ssot.h`) core macros, memory/safety barriers, SC0 UART0, and TBUS definitions.

use std::fmt::Write as _;

use crate::constants::events::DIGAOS_SERIAL_PROMPT;
use crate::constants::{
    AM34_IC7501_TBUS_BASE, AM34_IC7501_TBUS_TX_OFF, AM34_MAIN_BASE_VA, AM34_SC0_BASE,
    AM34_SC0_RXB_VA, AM34_SC0_STR_VA, AM34_SC0_TXB_VA, BGO_SECTOR_SIZE_64K,
    IC7501_TBUS_ACK_STROBE_BIT, IC7501_TBUS_CHECKSUM_BIAS, IC7501_VFD_TEXT_CMD,
    IC7501_WDT_KEEPALIVE_CMD, PANA_DIGADIAG_DEFAULT_LOAD_ADDR, PANA_DIGADIAG_RAW_VER061_SIZE,
};
use crate::re::{
    NOR_AUTOBOOT_CAPSULE_HEADER_BYTES, NOR_AUTOBOOT_CAPSULE_MAGIC_LE,
    NOR_AUTOBOOT_CAPSULE_MAGIC_OFFSET,
};
use crate::ssot::pico_header::{
    P7501_AM34_LETHAL_REG_LEN_SSOT, P7501_AM34_LETHAL_REG2_ADDR_SSOT, compute_pico_ssot_hash,
    resolve_eh55_verified_nor_context,
};

use super::header_sections::append_peripherals_storage_and_tables;
use super::{DIGAOS_SSOT_CONTRACT_HASH, DigaOsConfigSpec, load_validated_builtin_digaos_config};

const DIGAOS_SC0_TX_BUSY_MASK: u16 = 0x00A0;
const DIGAOS_SC0_RX_READY_MASK: u16 = 0x0010;
const DIGAOS_SC0_SPIN_LIMIT: u32 = 0x0004_0000;
const DIGAOS_SYSCON_DANGER_PAGE_BYTES: u32 = 0x1000;

pub(super) fn push_def_u32(out: &mut String, name: &str, val: u32, hex: bool) {
    if hex {
        let _ = writeln!(out, "#define {name:<38} 0x{val:08X}UL");
    } else {
        let _ = writeln!(out, "#define {name:<38} {val}UL");
    }
}

pub(super) fn push_def_u16(out: &mut String, name: &str, val: u16) {
    let _ = writeln!(out, "#define {name:<38} 0x{val:04X}U");
}

pub(super) fn push_def_u8(out: &mut String, name: &str, val: u8) {
    let _ = writeln!(out, "#define {name:<38} 0x{val:02X}U");
}

/// Renders `firmware/digaos/generated/digaos_ssot.h` deterministically from Rust SSOT + `profiles/`.
#[must_use]
pub fn generate_digaos_ssot_header_for(cfg: &DigaOsConfigSpec, contract_hash: u32) -> String {
    let ctx = resolve_eh55_verified_nor_context();
    let pico_ssot_hash = compute_pico_ssot_hash();
    let eemul_tag_1284_le = u32::from_le_bytes(*b"1284");
    let tbus_mbox = AM34_IC7501_TBUS_BASE + AM34_IC7501_TBUS_TX_OFF;

    let mut out = String::from(
        "/* AUTO-GENERATED BY panadiga-core::ssot::digaos_header -- DO NOT EDIT MANUALLY. */\n\
         /* HARDWARE-INTEROPERABILITY PROTOTYPE -- NOT LEGALLY CLEAN-ROOM. */\n\
         #ifndef PANADIGA_DIGAOS_GENERATED_SSOT_H\n\
         #define PANADIGA_DIGAOS_GENERATED_SSOT_H\n\n\
         #include <stdbool.h>\n\
         #include <stddef.h>\n\
         #include <stdint.h>\n\n",
    );
    let _ = writeln!(out, "#define DIGAOS_PROMPT \"{DIGAOS_SERIAL_PROMPT}\"");
    let _ = writeln!(
        out,
        "#define {:<38} 0x{contract_hash:08X}UL",
        "DIGAOS_SSOT_CONTRACT_HASH"
    );
    let _ = writeln!(
        out,
        "#define {:<38} 0x{pico_ssot_hash:08X}UL",
        "DIGAOS_SSOT_CONTRACT_HASH_U32"
    );
    let _ = writeln!(
        out,
        "#define {:<38} \"{contract_hash:08X}\"\n",
        "DIGAOS_SSOT_CONTRACT_HASH_STR"
    );

    push_def_u32(
        &mut out,
        "DIGAOS_SSOT_LETHAL_MMIO_START",
        ctx.lethal_mmio0,
        true,
    );
    push_def_u32(
        &mut out,
        "DIGAOS_SSOT_LETHAL_MMIO_END",
        ctx.lethal_mmio0 + P7501_AM34_LETHAL_REG_LEN_SSOT,
        true,
    );
    push_def_u32(
        &mut out,
        "DIGAOS_SSOT_SYSCON_DANGER_START",
        P7501_AM34_LETHAL_REG2_ADDR_SSOT,
        true,
    );
    push_def_u32(
        &mut out,
        "DIGAOS_SSOT_SYSCON_DANGER_END",
        P7501_AM34_LETHAL_REG2_ADDR_SSOT + DIGAOS_SYSCON_DANGER_PAGE_BYTES,
        true,
    );

    push_def_u32(
        &mut out,
        "DIGAOS_SSOT_IPL_CS0_BASE",
        ctx.nor_cached_base,
        true,
    );
    push_def_u32(
        &mut out,
        "DIGAOS_SSOT_IPL_CS0_END",
        ctx.nor_cached_base + ctx.ipl_size,
        true,
    );
    push_def_u32(
        &mut out,
        "DIGAOS_SSOT_IPL_CS1_BASE",
        ctx.nor_uncached_base,
        true,
    );
    push_def_u32(
        &mut out,
        "DIGAOS_SSOT_IPL_CS1_END",
        ctx.nor_uncached_base + ctx.ipl_size,
        true,
    );
    push_def_u32(
        &mut out,
        "DIGAOS_SSOT_NORFROM_SA11_BASE",
        ctx.nor_uncached_base + ctx.ipl_size,
        true,
    );
    push_def_u32(
        &mut out,
        "DIGAOS_SSOT_NORFROM_SA11_SIZE",
        u32::try_from(PANA_DIGADIAG_RAW_VER061_SIZE).expect("raw size u32"),
        true,
    );
    push_def_u32(
        &mut out,
        "DIGAOS_SSOT_NOR_AUTOBOOT_HDR_BYTES",
        u32::try_from(NOR_AUTOBOOT_CAPSULE_HEADER_BYTES).expect("capsule hdr bytes u32"),
        false,
    );
    push_def_u32(
        &mut out,
        "DIGAOS_SSOT_NOR_AUTOBOOT_MAGIC_OFFSET",
        u32::try_from(NOR_AUTOBOOT_CAPSULE_MAGIC_OFFSET).expect("capsule magic off u32"),
        true,
    );
    push_def_u32(
        &mut out,
        "DIGAOS_SSOT_NOR_AUTOBOOT_MAGIC_LE",
        NOR_AUTOBOOT_CAPSULE_MAGIC_LE,
        true,
    );
    push_def_u32(
        &mut out,
        "DIGAOS_SSOT_BGO_BASE",
        ctx.nor_uncached_base + ctx.bgo_offset,
        true,
    );
    let _ = writeln!(
        out,
        "#define {:<38} {}U",
        "DIGAOS_SSOT_BGO_SECTOR_COUNT", ctx.bgo_sector_count
    );
    push_def_u32(
        &mut out,
        "DIGAOS_SSOT_BGO_SECTOR_BYTES",
        BGO_SECTOR_SIZE_64K,
        true,
    );
    push_def_u32(
        &mut out,
        "DIGAOS_SSOT_EEMUL_BASE",
        ctx.nor_uncached_base + ctx.eemul_offset,
        true,
    );
    push_def_u32(&mut out, "DIGAOS_SSOT_EEMUL_SIZE", ctx.eemul_size, true);
    push_def_u32(
        &mut out,
        "DIGAOS_SSOT_EEMUL_TAG_1284_LE",
        eemul_tag_1284_le,
        true,
    );
    push_def_u32(
        &mut out,
        "DIGAOS_SSOT_PROG_RAM_BASE",
        PANA_DIGADIAG_DEFAULT_LOAD_ADDR,
        true,
    );
    push_def_u32(
        &mut out,
        "DIGAOS_SSOT_MAIN_RAM_BASE",
        AM34_MAIN_BASE_VA,
        true,
    );

    push_def_u32(&mut out, "DIGAOS_SSOT_SC0_CTR", AM34_SC0_BASE, true);
    push_def_u32(&mut out, "DIGAOS_SSOT_SC0_TXB", AM34_SC0_TXB_VA, true);
    push_def_u32(&mut out, "DIGAOS_SSOT_SC0_RXB", AM34_SC0_RXB_VA, true);
    push_def_u32(&mut out, "DIGAOS_SSOT_SC0_STR", AM34_SC0_STR_VA, true);
    push_def_u16(
        &mut out,
        "DIGAOS_SSOT_SC0_TX_BUSY_MASK",
        DIGAOS_SC0_TX_BUSY_MASK,
    );
    push_def_u16(
        &mut out,
        "DIGAOS_SSOT_SC0_RX_READY_MASK",
        DIGAOS_SC0_RX_READY_MASK,
    );
    push_def_u32(
        &mut out,
        "DIGAOS_SSOT_SC0_SPIN_LIMIT",
        DIGAOS_SC0_SPIN_LIMIT,
        true,
    );

    push_def_u32(
        &mut out,
        "DIGAOS_SSOT_TBUS_BASE",
        AM34_IC7501_TBUS_BASE,
        true,
    );
    push_def_u32(&mut out, "DIGAOS_SSOT_TBUS_MBOX", tbus_mbox, true);
    push_def_u8(
        &mut out,
        "DIGAOS_SSOT_TBUS_ACK_BIT",
        IC7501_TBUS_ACK_STROBE_BIT,
    );
    push_def_u8(
        &mut out,
        "DIGAOS_SSOT_TBUS_CSUM_BIAS",
        IC7501_TBUS_CHECKSUM_BIAS,
    );
    push_def_u8(
        &mut out,
        "DIGAOS_SSOT_TBUS_WDT_CMD",
        IC7501_WDT_KEEPALIVE_CMD,
    );
    push_def_u8(&mut out, "DIGAOS_SSOT_TBUS_VFD_CMD", IC7501_VFD_TEXT_CMD);

    append_peripherals_storage_and_tables(&mut out, cfg);
    out.push_str("#endif /* PANADIGA_DIGAOS_GENERATED_SSOT_H */\n");
    out
}

/// Renders `firmware/digaos/generated/digaos_ssot.h` using builtin `default_digaos_config.json`.
#[must_use]
pub fn generate_digaos_ssot_header() -> String {
    let cfg = load_validated_builtin_digaos_config();
    generate_digaos_ssot_header_for(&cfg, DIGAOS_SSOT_CONTRACT_HASH)
}
