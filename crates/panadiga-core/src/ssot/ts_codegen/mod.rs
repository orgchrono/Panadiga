fn tier_snake(tier: EvidenceTier) -> &'static str {
    match tier {
        EvidenceTier::CommunityUnverified => "community_unverified",
        EvidenceTier::ServiceManualOnly => "service_manual_only",
        EvidenceTier::OfficialFrmVerified => "official_frm_verified",
        EvidenceTier::PhysicalDumpVerified => "physical_dump_verified",
        EvidenceTier::BenchVerified => "bench_verified",
    }
}

/// Renders `apps/desktop/src/models/generated/ssot.ts` deterministically from Rust SSOT + `profiles/`.
pub fn generate_ts_ssot_module() -> String {
    let reg = HardwareProfileRegistry::builtin();
    let spec = build_hardware_ssot_spec();
    let models = reg.list_models();

    let mut out = String::new();
    out.push_str(
        "// AUTO-GENERATED BY panadiga-core::ssot::ts_codegen -- DO NOT EDIT MANUALLY.\n\n",
    );

    out.push_str("export const DIGA_MODEL_IDS = [\n");
    for m in &models {
        let _ = writeln!(out, "  '{}',", m.manifest.model_id);
    }
    out.push_str("] as const;\n");
    out.push_str("export type DigaModelId = (typeof DIGA_MODEL_IDS)[number];\n\n");

    let contract_hash = compute_pico_ssot_hash();
    let _ = writeln!(
        out,
        "export const SSOT_CONTRACT_HASH_U32 = 0x{contract_hash:08X};"
    );
    let _ = writeln!(
        out,
        "export const SSOT_CONTRACT_HASH_STR = '{contract_hash:08X}';\n"
    );

    out.push_str("export const SSOT_IPC_EVENTS = {\n");
    for &(sym, channel) in ALL_IPC_EVENT_CHANNELS {
        let _ = writeln!(out, "  {sym}: '{channel}',");
    }
    out.push_str("} as const;\n");
    out.push_str("export type SsotIpcEventName = (typeof SSOT_IPC_EVENTS)[keyof typeof SSOT_IPC_EVENTS];\n\n");

    out.push_str("export const SSOT_P7501_WIRE_TAGS = {\n");
    for &(sym, tag) in P7501_WIRE_TAGS {
        let _ = writeln!(out, "  {sym}: '{tag}',");
    }
    out.push_str("} as const;\n\n");

    out.push_str("export const SSOT_P7501_RES_CODES = {\n");
    for &(sym, code) in P7501_RES_CODES {
        let _ = writeln!(out, "  {sym}: '{code}',");
    }
    out.push_str("} as const;\n\n");

    out.push_str("export const PICO_COMMAND_IDS = [\n");
    for cmd in &spec.pico_commands {
        let _ = writeln!(out, "  '{}',", cmd.id);
    }
    out.push_str("] as const;\n");
    out.push_str("export type PicoCommandId = (typeof PICO_COMMAND_IDS)[number];\n\n");

    out.push_str(
        "export type EvidenceTier =\n\
         \x20 | 'community_unverified'\n\
         \x20 | 'service_manual_only'\n\
         \x20 | 'official_frm_verified'\n\
         \x20 | 'physical_dump_verified'\n\
         \x20 | 'bench_verified';\n\n\
         export type HardwareCapability =\n\
         \x20 | 'inspect_read_only'\n\
         \x20 | 'nvram_sanitize_offline_cow'\n\
         \x20 | 'nvram_write_live'\n\
         \x20 | 'upper_nor_patch_offline_cow'\n\
         \x20 | 'upper_nor_write_live'\n\
         \x20 | 'official_frm_pass_through'\n\
         \x20 | 'custom_recovery_media';\n\n\
         export interface SsotElectricalThresholdsMv {\n\
         \x20 readonly minVddMv: number;\n\
         \x20 readonly wakeMinMv: number;\n\
         \x20 readonly pulldownMinMv: number;\n\
         \x20 readonly safeOperatingMinMv: number;\n\
         \x20 readonly nominalVddMv: number;\n\
         \x20 readonly floatingCeilMv: number;\n\
         }\n\n\
         export const SSOT_ELECTRICAL_THRESHOLDS_MV: SsotElectricalThresholdsMv = {\n",
    );
    let _ = writeln!(out, "  minVddMv: {P7501_VDD_MIN_MV},");
    let _ = writeln!(out, "  wakeMinMv: {P7501_VDD_WAKE_MIN_MV},");
    let _ = writeln!(out, "  pulldownMinMv: {P7501_VDD_PULLDOWN_MIN_MV},");
    let _ = writeln!(out, "  safeOperatingMinMv: {P7501_VDD_SAFE_MIN_MV},");
    let _ = writeln!(out, "  nominalVddMv: {P7501_VDD_NOMINAL_MV},");
    let _ = writeln!(out, "  floatingCeilMv: {P7501_VDD_FLOATING_CEIL_MV},");
    out.push_str("} as const;\n\n");

    out.push_str(
        "export interface ResolvedSectorBankSummary {\n\
         \x20 readonly name: string;\n\
         \x20 readonly startSa: number;\n\
         \x20 readonly endSa: number;\n\
         \x20 readonly count: number;\n\
         \x20 readonly sectorSizeBytes: number;\n\
         }\n\n\
         export interface SsotModelProjection {\n\
         \x20 readonly modelId: DigaModelId;\n\
         \x20 readonly boardTier: EvidenceTier;\n\
         \x20 readonly flashPartNumber: string | null;\n\
         \x20 readonly derivedSectorGeometry: string | null;\n\
         \x20 readonly nvramUncachedVaHex: string | null;\n\
         \x20 readonly iplProtectedRangeHex: string | null;\n\
         \x20 readonly allowedCapabilities: readonly HardwareCapability[];\n\
         \x20 readonly sectorBanks: readonly ResolvedSectorBankSummary[];\n\
         }\n\n\
         export const SSOT_MODEL_PROJECTIONS: readonly SsotModelProjection[] = [\n",
    );

    for m in &models {
        let mut caps: Vec<&'static str> = vec!["inspect_read_only"];
        let c = &m.effective_capabilities;
        if c.nvram_sanitize_offline_cow {
            caps.push("nvram_sanitize_offline_cow");
        }
        if c.nvram_write_live {
            caps.push("nvram_write_live");
        }
        if c.upper_nor_patch_offline_cow {
            caps.push("upper_nor_patch_offline_cow");
        }
        if c.upper_nor_write_live {
            caps.push("upper_nor_write_live");
        }
        if c.official_frm_pass_through {
            caps.push("official_frm_pass_through");
        }
        if c.custom_recovery_media {
            caps.push("custom_recovery_media");
        }

        out.push_str("  {\n");
        let _ = writeln!(out, "    modelId: '{}',", m.manifest.model_id);
        let _ = writeln!(
            out,
            "    boardTier: '{}',",
            tier_snake(m.manifest.claims.board.tier)
        );
        if let Some(chip) = &m.flash_chip {
            let _ = writeln!(out, "    flashPartNumber: '{}',", chip.part_number);
        } else {
            out.push_str("    flashPartNumber: null,\n");
        }
        if let Some(geo) = &m.derived_sector_geometry {
            let escaped = geo.replace('\'', "\\'");
            let _ = writeln!(out, "    derivedSectorGeometry: '{escaped}',");
        } else {
            out.push_str("    derivedSectorGeometry: null,\n");
        }
        if let Some(nv) = &m.nvram_uncached_va_hex {
            let _ = writeln!(out, "    nvramUncachedVaHex: '{nv}',");
        } else {
            out.push_str("    nvramUncachedVaHex: null,\n");
        }
        if let Some(ipl) = &m.ipl_protected_range_hex {
            let _ = writeln!(out, "    iplProtectedRangeHex: '{ipl}',");
        } else {
            out.push_str("    iplProtectedRangeHex: null,\n");
        }
        let caps_joined: Vec<String> = caps.into_iter().map(|s| format!("'{s}'")).collect();
        let _ = writeln!(
            out,
            "    allowedCapabilities: [{}],",
            caps_joined.join(", ")
        );

        out.push_str("    sectorBanks: [");
        if let Some(chip) = &m.flash_chip {
            let _table = derive_sector_table(chip).ok();
            let mut next_sa = 0u32;
            for b in &chip.sector_banks {
                let end_sa = next_sa + b.count - 1;
                let _ = write!(
                    out,
                    "{{ name: '{}', startSa: {next_sa}, endSa: {end_sa}, count: {}, sectorSizeBytes: {} }}, ",
                    b.name, b.count, b.sector_size
                );
                next_sa = end_sa + 1;
            }
        }
        out.push_str("],\n  },\n");
    }
    out.push_str("];\n\n");

    out.push_str(
        "export interface SsotDiagSignatureRule {\n\
         \x20 readonly needle: string;\n\
         \x20 readonly eventSymbol: string;\n\
         }\n\n\
         export const SSOT_DIAG_SIGNATURE_RULES: readonly SsotDiagSignatureRule[] = [\n",
    );
    for &(needle, sym) in DIAG_SIGNATURE_RULES {
        let escaped = needle.replace('\\', "\\\\").replace('\'', "\\'");
        let _ = writeln!(out, "  {{ needle: '{escaped}', eventSymbol: '{sym}' }},");
    }
    out.push_str("];\n\n");
    out.push_str(
        "export const SSOT_WIRE_TERMINAL_MARKERS = [\n\
         \x20 '@P7501_RES ',\n\
         \x20 'PANADIGA>',\n\
         \x20 'P7501>',\n\
         ] as const;\n\n",
    );

    let eh55_lethal = reg
        .resolve_model("DMR-EH55")
        .ok()
        .and_then(|m| m.soc)
        .and_then(|s| s.lethal_mmio.first().copied())
        .expect("DMR-EH55 SoC lethal_mmio required");

    out.push_str(
        "export interface SsotAm34BusConstants {\n\
         \x20 readonly flashCachedBaseAddr: number;\n\
         \x20 readonly flashCachedBaseHex: string;\n\
         \x20 readonly flashUncachedBaseAddr: number;\n\
         \x20 readonly flashUncachedBaseHex: string;\n\
         \x20 readonly nvramCachedBaseAddr: number;\n\
         \x20 readonly nvramCachedBaseHex: string;\n\
         \x20 readonly nvramUncachedBaseAddr: number;\n\
         \x20 readonly nvramUncachedBaseHex: string;\n\
         \x20 readonly digadiagLoadAddrHex: string;\n\
         \x20 readonly sdramStubRawAddrHex: string;\n\
         \x20 readonly lethalMmioRegAddr: number;\n\
         \x20 readonly lethalMmioRegHex: string;\n\
         \x20 readonly defaultBaudRate: number;\n\
         \x20 readonly wdtMaxCmdWindowMs: number;\n\
         }\n\n\
         export const SSOT_AM34_BUS_CONSTANTS: SsotAm34BusConstants = {\n",
    );
    let _ = writeln!(out, "  flashCachedBaseAddr: 0x{AM34_FLASH_BASE:08x},");
    let _ = writeln!(out, "  flashCachedBaseHex: '0x{AM34_FLASH_BASE:08X}',");
    let _ = writeln!(
        out,
        "  flashUncachedBaseAddr: 0x{AM34_FLASH_UNCACHED_BASE:08x},"
    );
    let _ = writeln!(
        out,
        "  flashUncachedBaseHex: '0x{AM34_FLASH_UNCACHED_BASE:08X}',"
    );
    let _ = writeln!(out, "  nvramCachedBaseAddr: 0x{AM34_NVRAM_BASE:08x},");
    let _ = writeln!(out, "  nvramCachedBaseHex: '0x{AM34_NVRAM_BASE:08X}',");
    let _ = writeln!(
        out,
        "  nvramUncachedBaseAddr: 0x{AM34_NVRAM_UNCACHED_BASE:08x},"
    );
    let _ = writeln!(
        out,
        "  nvramUncachedBaseHex: '0x{AM34_NVRAM_UNCACHED_BASE:08X}',"
    );
    let _ = writeln!(
        out,
        "  digadiagLoadAddrHex: '0x{PANA_DIGADIAG_DEFAULT_LOAD_ADDR:08X}',"
    );
    let _ = writeln!(
        out,
        "  sdramStubRawAddrHex: '0x{AM34_SDRAM_STUB_RAW_ADDR:08X}',"
    );
    let _ = writeln!(out, "  lethalMmioRegAddr: 0x{eh55_lethal:08x},");
    let _ = writeln!(out, "  lethalMmioRegHex: '0x{eh55_lethal:08X}',");
    let _ = writeln!(out, "  defaultBaudRate: {DEFAULT_BAUD_RATE},");
    let _ = writeln!(out, "  wdtMaxCmdWindowMs: {P7501_WDT_MAX_CMD_WINDOW_MS},");
    out.push_str("} as const;\n\n");
    append_bench_stream_contracts(&mut out);
    out
}

/// Exports TypeScript SSOT projection to `apps/desktop/src/models/generated/ssot.ts`.
pub fn export_ts_ssot_module(output_path: &Path) -> Result<()> {
    super::pico_header::write_if_changed_or_create(output_path, &generate_ts_ssot_module())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_ts_ssot_matches_checked_in_module() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../apps/desktop/src/models/generated/ssot.ts");
        let on_disk = fs::read_to_string(&path)
            .unwrap_or_else(|e| panic!("Missing checked-in {}: {e}", path.display()));
        let generated = generate_ts_ssot_module();
        assert_eq!(
            on_disk.replace("\r\n", "\n"),
            generated,
            "apps/desktop/src/models/generated/ssot.ts is out of sync (run `panadiga ssot export-all`)"
        );
        assert!(generated.contains("'DMR-EH55'"));
        assert!(generated.contains("'DMR-ES35V'"));
        assert!(generated.contains("minVddMv: 2500"));
    }
}
