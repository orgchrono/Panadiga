#![deny(unsafe_code)]

//! Deterministic compiler projecting `panadiga-profiles` v2 contracts into:
//! - TypeScript (`apps/desktop/src/models/generated/profiles.ts`)
//! - Strict Python 3.10+ (`scripts/profiles_types.py`)

mod py_emit;
mod ts_emit_core;
mod ts_emit_models;

use std::fmt::Write as _;
#[cfg(test)]
use std::fs;
use std::path::Path;

use anyhow::Result;

use super::pico_header::{compute_pico_ssot_hash, write_if_changed_or_create};
use py_emit::PY_PROFILES_TYPES_BODY;
use ts_emit_core::TS_PROFILES_TYPES_CORE;
use ts_emit_models::TS_PROFILES_TYPES_MODELS;

/// Renders `apps/desktop/src/models/generated/profiles.ts` deterministically from Rust SSOT contracts.
#[must_use]
pub fn generate_ts_profiles_module() -> String {
    let mut out =
        String::with_capacity(TS_PROFILES_TYPES_CORE.len() + TS_PROFILES_TYPES_MODELS.len());
    out.push_str(TS_PROFILES_TYPES_CORE);
    out.push_str(TS_PROFILES_TYPES_MODELS);
    out
}

/// Exports `apps/desktop/src/models/generated/profiles.ts`.
pub fn export_ts_profiles_module(output_path: &Path) -> Result<()> {
    write_if_changed_or_create(output_path, &generate_ts_profiles_module())
}

/// Renders strict Python 3.10+ TypedDict/Literal mirrors for `scripts/profiles_types.py`.
#[must_use]
pub fn generate_python_profiles_types() -> String {
    let ssot_hash = compute_pico_ssot_hash();
    let mut out = String::from(
        "\"\"\"AUTO-GENERATED BY panadiga-core::ssot::profiles_codegen -- DO NOT EDIT MANUALLY.\"\"\"\n\n",
    );
    out.push_str(PY_PROFILES_TYPES_BODY);
    out.push_str("\nSAFE_BENCH_COMMANDS: Final[tuple[str, ...]] = (\n");
    for cmd in crate::pico::bench_decoders::SAFE_BENCH_COMMANDS {
        let _ = writeln!(out, "    \"{cmd}\",");
    }
    out.push_str(")\n\nFORBIDDEN_BENCH_TOKENS: Final[tuple[str, ...]] = (\n");
    for tok in crate::pico::bench_decoders::FORBIDDEN_BENCH_TOKENS {
        let _ = writeln!(out, "    \"{tok}\",");
    }
    let _ = writeln!(
        out,
        ")\n\nSSOT_CONTRACT_HASH_STR: Final[str] = \"{ssot_hash:08X}\"\n\nP7501_WIRE_TAGS: Final[dict[str, str]] = {{"
    );
    for &(sym, tag) in crate::constants::events::P7501_WIRE_TAGS {
        let _ = writeln!(out, "    \"{sym}\": \"{tag}\",");
    }
    out.push_str("}\n\nP7501_RES_CODES: Final[dict[str, str]] = {\n");
    for &(sym, code) in crate::constants::events::P7501_RES_CODES {
        let _ = writeln!(out, "    \"{sym}\": \"{code}\",");
    }
    out.push_str("}\n");
    out
}

/// Exports `scripts/profiles_types.py`.
pub fn export_python_profiles_types(output_path: &Path) -> Result<()> {
    write_if_changed_or_create(output_path, &generate_python_profiles_types())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_profiles_ts_and_python_match_checked_in_modules() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
        let ts_path = root.join("apps/desktop/src/models/generated/profiles.ts");
        let py_path = root.join("scripts/profiles_types.py");

        let ts_disk = fs::read_to_string(&ts_path)
            .unwrap_or_else(|e| panic!("Missing {}: {e}", ts_path.display()));
        assert_eq!(
            ts_disk.replace("\r\n", "\n"),
            generate_ts_profiles_module(),
            "apps/desktop/src/models/generated/profiles.ts is out of sync (run `panadiga ssot export-all`)"
        );

        let py_disk = fs::read_to_string(&py_path)
            .unwrap_or_else(|e| panic!("Missing {}: {e}", py_path.display()));
        assert_eq!(
            py_disk.replace("\r\n", "\n"),
            generate_python_profiles_types(),
            "scripts/profiles_types.py is out of sync (run `panadiga ssot export-all`)"
        );
    }
}
