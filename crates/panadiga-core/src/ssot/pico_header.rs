//! Deterministic C11 SSOT header generator for Pico `P7501` (`PANARSP` / `_dev_SERIAL`).

use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use anyhow::{Context, Result};

use crate::re::main_passthrough::{
    DEV_SERIAL_CALLBACK_VA, DEV_SERIAL_HANDSHAKE_BYTES, DEV_SERIAL_ISR_CTX_PTR_VA,
    DEV_SERIAL_PC_OFFSET, passthrough_rsp_payloads,
};

/// Single-byte `_dev_SERIAL` RSP entry ACK/NAK strobe confirmed empirically in `3410PQ`.
pub const DEV_SERIAL_NAK_BYTE: u8 = 0x15;

/// Renders `firmware/pico-p7501/uart/p7501_pana_rsp_ssot.h` purely from Rust SSOT constants.
pub fn generate_pana_rsp_ssot_header() -> String {
    let mut out = String::new();
    out.push_str(
        "/* AUTO-GENERATED BY panadiga-core::ssot::pico_header -- DO NOT EDIT MANUALLY. */\n",
    );
    out.push_str("#ifndef P7501_PANA_RSP_SSOT_H\n");
    out.push_str("#define P7501_PANA_RSP_SSOT_H\n\n");

    let _ = writeln!(
        out,
        "#define P7501_RSP_HANDSHAKE_LEN {}u",
        DEV_SERIAL_HANDSHAKE_BYTES.len()
    );
    let hex_elems: Vec<String> = DEV_SERIAL_HANDSHAKE_BYTES
        .iter()
        .map(|b| format!("0x{b:02X}u"))
        .collect();
    let _ = writeln!(
        out,
        "#define P7501_RSP_HANDSHAKE_INIT {{ {} }}",
        hex_elems.join(", ")
    );
    let _ = writeln!(
        out,
        "#define P7501_RSP_NAK_BYTE 0x{DEV_SERIAL_NAK_BYTE:02X}u\n"
    );

    let _ = writeln!(
        out,
        "#define P7501_AM34_ISR_CTX_PTR_ADDR   0x{DEV_SERIAL_ISR_CTX_PTR_VA:08X}UL"
    );
    let _ = writeln!(
        out,
        "#define P7501_AM34_ISR_SAVED_PC_OFF   0x{DEV_SERIAL_PC_OFFSET:02X}UL"
    );
    let _ = writeln!(
        out,
        "#define P7501_AM34_SERIAL_CB_PTR_ADDR 0x{DEV_SERIAL_CALLBACK_VA:08X}UL\n"
    );

    let payloads = passthrough_rsp_payloads();
    let _ = writeln!(
        out,
        "#define P7501_TBC_PASSTHROUGH_SEQ_LEN {}u",
        payloads.len()
    );
    out.push_str("#define P7501_TBC_PASSTHROUGH_SEQ_INIT { \\\n");
    for payload in &payloads {
        let _ = writeln!(out, "    \"{payload}\", \\");
    }
    out.push_str("}\n\n");
    out.push_str("#endif /* P7501_PANA_RSP_SSOT_H */\n");
    out
}

/// Writes `p7501_pana_rsp_ssot.h` to the given destination path.
pub fn export_pico_rsp_ssot_header(output_path: &Path) -> Result<()> {
    if let Some(parent) = output_path.parent()
        && !parent.as_os_str().is_empty()
    {
        fs::create_dir_all(parent)
            .with_context(|| format!("Failed creating directory {}", parent.display()))?;
    }
    fs::write(output_path, generate_pana_rsp_ssot_header())
        .with_context(|| format!("Failed writing {}", output_path.display()))?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_pico_rsp_header_matches_checked_in_c_header() {
        let header_path = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../firmware/pico-p7501/uart/p7501_pana_rsp_ssot.h");
        let on_disk = fs::read_to_string(&header_path)
            .unwrap_or_else(|e| panic!("Missing checked-in {}: {e}", header_path.display()));
        assert_eq!(
            on_disk.replace("\r\n", "\n"),
            generate_pana_rsp_ssot_header(),
            "firmware/pico-p7501/uart/p7501_pana_rsp_ssot.h is out of sync with Rust SSOT"
        );
    }
}
