#![deny(unsafe_code)]

//! Deterministic C11 SSOT header emitter for `Panadiga OpenOS` (`firmware/panadiga-openos/generated/openos_ssot.h`).
//!
//! Eliminates manual hexadecimal constant duplication in `hal/am34_mmio.h` and `drivers/` by projecting
//! hardware bounds, MMIO apertures, TBUS/AIOF/AVDD/IIC/SDCD/DAVIS/MEIHFS definitions, and `SSOT_CONTRACT_HASH`
//! straight from `panadiga-constants` and `panadiga-profiles` (`DMR-EH55` `BenchVerified`).

use std::fmt::Write as _;
use std::path::Path;

use anyhow::Result;

use crate::constants::{
    AIOF_CONT_OFF, AIOF_CONT_SETUP_0IRE_LIGHTER, AIOF_CONT_SETUP_75IRE_DARKER,
    AIOF_FS0_NON_STANDARD, AIOF_FS0_OFF, AIOF_FS0_STANDARD, AIOF_V_CLOCK_START, AIOF_V_OFF,
    AIOF_VMODESEL_NTSC, AIOF_VMODESEL_OFF, AIOF_VMODESEL_PAL, AIOF_VMODESEL_PAL_M,
    AIOF_YC3_MVAGC_LINE_TBC_BIT, AIOF_YC3_OFF, AM34_AIOF_BASE, AM34_AVDD_BASE,
    AM34_IC7501_TBUS_BASE, AM34_IC7501_TBUS_TX_OFF, AM34_IIC0_BASE, AM34_IIC1_BASE,
    AM34_MAIN_BASE_VA, AM34_SC0_BASE, AM34_SC0_RXB_VA, AM34_SC0_STR_VA, AM34_SC0_TXB_VA,
    AM34_SDCD_BUS_CFG_VA, AM34_SDCD_MMIO_BASE, AVDD_DACOUT1_OFF, AVDD_NPALCTL0_OFF,
    AVDD_REC656IN_OFF, AVDD_VDECCTL1_OFF, AVDD_VOUTMODE0_OFF, BGO_SECTOR_SIZE_64K,
    IC3001_I2C_ADDR_8BIT_WRITE, IC7501_TBUS_ACK_STROBE_BIT, IC7501_TBUS_CHECKSUM_BIAS,
    IC7501_VFD_TEXT_CMD, IC7501_WDT_KEEPALIVE_CMD, LBA_JOURNAL_CATALOG_OFFSET,
    LBA_MIRROR_MBR_SECTOR, LBA_PARTITION_1_SECTOR, LBA_SECTOR_SIZE_BYTES,
    PANA_DIGADIAG_DEFAULT_LOAD_ADDR, PANA_DIGADIAG_RAW_VER061_SIZE,
};
use crate::hdd::capacity_patch::specs::DYNAMIC_UNCLAMPED_MAX_BLOCKS_2KB;
use crate::re::davis_probe::{
    DAVIS_CH0_CONTROL_REG_VA, DAVIS_CH1_CONTROL_REG_VA, DAVIS_CH1_RESET_REG_VA,
};

use super::pico_header::{
    P7501_AM34_LETHAL_REG_LEN_SSOT, P7501_AM34_LETHAL_REG2_ADDR_SSOT,
    P7501_AM34_LETHAL_REG2_LEN_SSOT, compute_pico_ssot_hash, resolve_eh55_verified_nor_context,
    write_if_changed_or_create,
};

const OPENOS_SC0_TX_BUSY_MASK: u16 = 0x00A0;
const OPENOS_SC0_RX_READY_MASK: u16 = 0x0010;
const OPENOS_SC0_SPIN_LIMIT: u32 = 0x0004_0000;
const OPENOS_DAVIS_CH0_BASE_ADDR: u32 = 0x8900_0400;
const OPENOS_MIN_DISK_LBA_5GB: u32 = 0x0093_0E20;
const OPENOS_SATA_BRIDGE_WAIT_MS: u32 = 1_000;

fn push_def_u32(out: &mut String, name: &str, val: u32, hex: bool) {
    if hex {
        let _ = writeln!(out, "#define {name:<38} 0x{val:08X}UL");
    } else {
        let _ = writeln!(out, "#define {name:<38} {val}UL");
    }
}

fn push_def_u16(out: &mut String, name: &str, val: u16) {
    let _ = writeln!(out, "#define {name:<38} 0x{val:04X}U");
}

fn push_def_u8(out: &mut String, name: &str, val: u8) {
    let _ = writeln!(out, "#define {name:<38} 0x{val:02X}U");
}

/// Renders `firmware/panadiga-openos/generated/openos_ssot.h` deterministically from Rust SSOT + `profiles/`.
#[must_use]
pub fn generate_openos_ssot_header() -> String {
    let ctx = resolve_eh55_verified_nor_context();
    let ssot_hash = compute_pico_ssot_hash();
    let eemul_tag_1284_le = u32::from_le_bytes(*b"1284");
    let tbus_mbox = AM34_IC7501_TBUS_BASE + AM34_IC7501_TBUS_TX_OFF;

    let mut out = String::from(
        "/* AUTO-GENERATED BY panadiga-core::ssot::openos_header -- DO NOT EDIT MANUALLY. */\n\
         /* HARDWARE-INTEROPERABILITY PROTOTYPE -- NOT LEGALLY CLEAN-ROOM. */\n\
         #ifndef PANADIGA_OPENOS_GENERATED_SSOT_H\n\
         #define PANADIGA_OPENOS_GENERATED_SSOT_H\n\n",
    );
    push_def_u32(&mut out, "OPENOS_SSOT_CONTRACT_HASH_U32", ssot_hash, true);
    let _ = writeln!(
        out,
        "#define {:<38} \"{ssot_hash:08X}\"\n",
        "OPENOS_SSOT_CONTRACT_HASH_STR"
    );

    push_def_u32(
        &mut out,
        "OPENOS_SSOT_LETHAL_MMIO_START",
        ctx.lethal_mmio0,
        true,
    );
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_LETHAL_MMIO_END",
        ctx.lethal_mmio0 + P7501_AM34_LETHAL_REG_LEN_SSOT,
        true,
    );
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_SYSCON_DANGER_START",
        P7501_AM34_LETHAL_REG2_ADDR_SSOT,
        true,
    );
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_SYSCON_DANGER_END",
        P7501_AM34_LETHAL_REG2_ADDR_SSOT + 0x1000,
        true,
    );
    let _ = P7501_AM34_LETHAL_REG2_LEN_SSOT;

    push_def_u32(
        &mut out,
        "OPENOS_SSOT_IPL_CS0_BASE",
        ctx.nor_cached_base,
        true,
    );
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_IPL_CS0_END",
        ctx.nor_cached_base + ctx.ipl_size,
        true,
    );
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_IPL_CS1_BASE",
        ctx.nor_uncached_base,
        true,
    );
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_IPL_CS1_END",
        ctx.nor_uncached_base + ctx.ipl_size,
        true,
    );
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_NORFROM_SA11_BASE",
        ctx.nor_uncached_base + ctx.ipl_size,
        true,
    );
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_NORFROM_SA11_SIZE",
        u32::try_from(PANA_DIGADIAG_RAW_VER061_SIZE).expect("raw size u32"),
        true,
    );
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_BGO_BASE",
        ctx.nor_uncached_base + ctx.bgo_offset,
        true,
    );
    let _ = writeln!(
        out,
        "#define {:<38} {}U",
        "OPENOS_SSOT_BGO_SECTOR_COUNT", ctx.bgo_sector_count
    );
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_BGO_SECTOR_BYTES",
        BGO_SECTOR_SIZE_64K,
        true,
    );
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_EEMUL_BASE",
        ctx.nor_uncached_base + ctx.eemul_offset,
        true,
    );
    push_def_u32(&mut out, "OPENOS_SSOT_EEMUL_SIZE", ctx.eemul_size, true);
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_EEMUL_TAG_1284_LE",
        eemul_tag_1284_le,
        true,
    );
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_STAGE15_BASE",
        PANA_DIGADIAG_DEFAULT_LOAD_ADDR,
        true,
    );
    push_def_u32(&mut out, "OPENOS_SSOT_STAGE2_BASE", AM34_MAIN_BASE_VA, true);

    push_def_u32(&mut out, "OPENOS_SSOT_SC0_CTR", AM34_SC0_BASE, true);
    push_def_u32(&mut out, "OPENOS_SSOT_SC0_TXB", AM34_SC0_TXB_VA, true);
    push_def_u32(&mut out, "OPENOS_SSOT_SC0_RXB", AM34_SC0_RXB_VA, true);
    push_def_u32(&mut out, "OPENOS_SSOT_SC0_STR", AM34_SC0_STR_VA, true);
    push_def_u16(
        &mut out,
        "OPENOS_SSOT_SC0_TX_BUSY_MASK",
        OPENOS_SC0_TX_BUSY_MASK,
    );
    push_def_u16(
        &mut out,
        "OPENOS_SSOT_SC0_RX_READY_MASK",
        OPENOS_SC0_RX_READY_MASK,
    );
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_SC0_SPIN_LIMIT",
        OPENOS_SC0_SPIN_LIMIT,
        true,
    );

    push_def_u32(
        &mut out,
        "OPENOS_SSOT_TBUS_BASE",
        AM34_IC7501_TBUS_BASE,
        true,
    );
    push_def_u32(&mut out, "OPENOS_SSOT_TBUS_MBOX", tbus_mbox, true);
    push_def_u8(
        &mut out,
        "OPENOS_SSOT_TBUS_ACK_BIT",
        IC7501_TBUS_ACK_STROBE_BIT,
    );
    push_def_u8(
        &mut out,
        "OPENOS_SSOT_TBUS_CSUM_BIAS",
        IC7501_TBUS_CHECKSUM_BIAS,
    );
    push_def_u8(
        &mut out,
        "OPENOS_SSOT_TBUS_WDT_CMD",
        IC7501_WDT_KEEPALIVE_CMD,
    );
    push_def_u8(&mut out, "OPENOS_SSOT_TBUS_VFD_CMD", IC7501_VFD_TEXT_CMD);

    push_def_u32(&mut out, "OPENOS_SSOT_AIOF_BASE", AM34_AIOF_BASE, true);
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_AIOF_VMODESEL_OFF",
        AIOF_VMODESEL_OFF,
        true,
    );
    push_def_u32(&mut out, "OPENOS_SSOT_AIOF_FS0_OFF", AIOF_FS0_OFF, true);
    push_def_u16(&mut out, "OPENOS_SSOT_AIOF_FS0_STD", AIOF_FS0_STANDARD);
    push_def_u16(
        &mut out,
        "OPENOS_SSOT_AIOF_FS0_NONSTD",
        AIOF_FS0_NON_STANDARD,
    );
    push_def_u32(&mut out, "OPENOS_SSOT_AIOF_YC3_OFF", AIOF_YC3_OFF, true);
    push_def_u16(
        &mut out,
        "OPENOS_SSOT_AIOF_YC3_MVAGC",
        AIOF_YC3_MVAGC_LINE_TBC_BIT,
    );
    push_def_u32(&mut out, "OPENOS_SSOT_AIOF_V_OFF", AIOF_V_OFF, true);
    push_def_u16(&mut out, "OPENOS_SSOT_AIOF_V_ENABLE", AIOF_V_CLOCK_START);
    push_def_u32(&mut out, "OPENOS_SSOT_AIOF_CONT_OFF", AIOF_CONT_OFF, true);
    push_def_u16(
        &mut out,
        "OPENOS_SSOT_AIOF_CONT_0IRE",
        AIOF_CONT_SETUP_0IRE_LIGHTER,
    );
    push_def_u16(
        &mut out,
        "OPENOS_SSOT_AIOF_CONT_75IRE",
        AIOF_CONT_SETUP_75IRE_DARKER,
    );
    push_def_u16(&mut out, "OPENOS_SSOT_VMODESEL_NTSC", AIOF_VMODESEL_NTSC);
    push_def_u16(&mut out, "OPENOS_SSOT_VMODESEL_PAL_M", AIOF_VMODESEL_PAL_M);
    push_def_u16(&mut out, "OPENOS_SSOT_VMODESEL_PAL", AIOF_VMODESEL_PAL);

    push_def_u32(&mut out, "OPENOS_SSOT_AVDD_BASE", AM34_AVDD_BASE, true);
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_AVDD_DACOUT1_OFF",
        AVDD_DACOUT1_OFF,
        true,
    );
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_AVDD_VOUTMODE0_OFF",
        AVDD_VOUTMODE0_OFF,
        true,
    );
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_AVDD_REC656IN_OFF",
        AVDD_REC656IN_OFF,
        true,
    );
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_AVDD_NPALCTL0_OFF",
        AVDD_NPALCTL0_OFF,
        true,
    );
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_AVDD_VDECCTL1_OFF",
        AVDD_VDECCTL1_OFF,
        true,
    );

    push_def_u32(&mut out, "OPENOS_SSOT_IIC0_BASE", AM34_IIC0_BASE, true);
    push_def_u32(&mut out, "OPENOS_SSOT_IIC1_BASE", AM34_IIC1_BASE, true);
    push_def_u8(
        &mut out,
        "OPENOS_SSOT_IC3001_EC_ADDR8",
        IC3001_I2C_ADDR_8BIT_WRITE,
    );
    push_def_u32(&mut out, "OPENOS_SSOT_SDCD_BASE", AM34_SDCD_MMIO_BASE, true);
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_SDCD_BUS_CFG",
        AM34_SDCD_BUS_CFG_VA,
        true,
    );

    push_def_u32(
        &mut out,
        "OPENOS_SSOT_DAVIS_CH0_BASE",
        OPENOS_DAVIS_CH0_BASE_ADDR,
        true,
    );
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_DAVIS_CH0_RST",
        DAVIS_CH0_CONTROL_REG_VA,
        true,
    );
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_DAVIS_CH1_BASE",
        DAVIS_CH1_CONTROL_REG_VA,
        true,
    );
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_DAVIS_CH1_RST",
        DAVIS_CH1_RESET_REG_VA,
        true,
    );
    let wait_ms = OPENOS_SATA_BRIDGE_WAIT_MS;
    let _ = writeln!(
        out,
        "#define {:<38} {wait_ms}U",
        "OPENOS_SSOT_SATA_BRIDGE_WAIT_MS"
    );

    push_def_u32(
        &mut out,
        "OPENOS_SSOT_SECTOR_BYTES",
        u32::try_from(LBA_SECTOR_SIZE_BYTES).expect("sector bytes u32"),
        false,
    );
    push_def_u32(&mut out, "OPENOS_SSOT_MEIHFS_MBR_LBA", 0, false);
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_MEIHFS_JOURNAL_LBA",
        u32::try_from(LBA_JOURNAL_CATALOG_OFFSET / LBA_SECTOR_SIZE_BYTES as u64)
            .expect("journal lba u32"),
        false,
    );
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_MEIHFS_MBR_MIRROR_LBA",
        u32::try_from(LBA_MIRROR_MBR_SECTOR).expect("mirror lba u32"),
        false,
    );
    let pri_fw = u32::try_from(LBA_PARTITION_1_SECTOR).expect("pri fw lba u32");
    push_def_u32(&mut out, "OPENOS_SSOT_MEIHFS_PRIMARY_FW_LBA", pri_fw, true);
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_MEIHFS_MIRROR_DELTA_LBA",
        pri_fw * 2,
        true,
    );
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_MEIHFS_MIN_DISK_LBA",
        OPENOS_MIN_DISK_LBA_5GB,
        true,
    );
    push_def_u32(
        &mut out,
        "OPENOS_SSOT_MEIHFS_MAX_BLOCKS_2KB",
        DYNAMIC_UNCLAMPED_MAX_BLOCKS_2KB,
        true,
    );

    out.push_str("\n#endif /* PANADIGA_OPENOS_GENERATED_SSOT_H */\n");
    out
}

/// Exports `firmware/panadiga-openos/generated/openos_ssot.h`.
pub fn export_openos_ssot_header(output_path: &Path) -> Result<()> {
    write_if_changed_or_create(output_path, &generate_openos_ssot_header())
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;

    #[test]
    fn generated_openos_ssot_matches_checked_in_header_and_invariants() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../firmware/panadiga-openos/generated/openos_ssot.h");
        let on_disk = fs::read_to_string(&path)
            .unwrap_or_else(|e| panic!("Missing checked-in {}: {e}", path.display()));
        let generated = generate_openos_ssot_header();
        assert_eq!(
            on_disk.replace("\r\n", "\n"),
            generated,
            "firmware/panadiga-openos/generated/openos_ssot.h is out of sync (run `panadiga ssot export-all`)"
        );
        assert!(generated.contains("0xC000100CUL"));
        assert!(generated.contains("0x80000000UL"));
        assert!(generated.contains("0x84040000UL"));
        assert!(generated.contains("0x84130000UL"));
        assert!(generated.contains("1000U"));
        assert!(generated.contains("0x0010U"));
    }
}
