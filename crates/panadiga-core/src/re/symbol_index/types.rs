#![deny(unsafe_code)]

//! Core data contracts for the Panadiga deterministic Firmware Symbol & Callers Dictionary
//! (`profiles/symbols/<firmware_train_id>/<module>.json`).
//!
//! Indexes are keyed strictly by firmware train and module (`firmware_train_id`, `module`,
//! `sha256`, `base_va`) without coupling to commercial model names.

use serde::{Deserialize, Serialize};
use std::str::FromStr;

/// Side-effect classification used by MCP/RAG safety gates to block unattended destructive calls.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum SymbolSideEffect {
    ReadOnly,
    WritesNorBgo,
    WritesHdd,
    WritesNvram,
    WritesMmio,
    Unknown,
}

impl SymbolSideEffect {
    /// Returns `true` when calling the function mutates persistent flash/NVRAM/HDD state.
    #[must_use]
    pub const fn is_destructive(self) -> bool {
        matches!(
            self,
            Self::WritesNorBgo | Self::WritesHdd | Self::WritesNvram
        )
    }

    /// Canonical snake_case string token matching JSON serialization.
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::ReadOnly => "read_only",
            Self::WritesNorBgo => "writes_nor_bgo",
            Self::WritesHdd => "writes_hdd",
            Self::WritesNvram => "writes_nvram",
            Self::WritesMmio => "writes_mmio",
            Self::Unknown => "unknown",
        }
    }
}

impl FromStr for SymbolSideEffect {
    type Err = anyhow::Error;

    fn from_str(raw: &str) -> anyhow::Result<Self> {
        match raw.trim().to_ascii_lowercase().as_str() {
            "read_only" => Ok(Self::ReadOnly),
            "writes_nor_bgo" => Ok(Self::WritesNorBgo),
            "writes_hdd" => Ok(Self::WritesHdd),
            "writes_nvram" => Ok(Self::WritesNvram),
            "writes_mmio" => Ok(Self::WritesMmio),
            "unknown" => Ok(Self::Unknown),
            other => anyhow::bail!(
                "Invalid side_effect '{other}': expected read_only, writes_nor_bgo, writes_hdd, writes_nvram, writes_mmio, or unknown"
            ),
        }
    }
}

/// Structured MN103S register/stack calling convention breakdown.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SymbolAbiDetail {
    pub params: Vec<String>,
    pub saved_regs: Vec<String>,
    pub frame_bytes: Option<u8>,
}

/// Single deterministic symbol record emitted into `profiles/symbols/<train>/<module>.json`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct FunctionSymbolEntry {
    pub va: String,
    pub end_va: String,
    pub name: String,
    pub abi: String,
    pub abi_detail: SymbolAbiDetail,
    pub ret: String,
    pub callers: Vec<String>,
    pub callees: Vec<String>,
    pub string_xrefs: Vec<String>,
    pub mmio_xrefs: Vec<String>,
    pub side_effects: SymbolSideEffect,
    pub side_effect_reasons: Vec<String>,
    pub evidence_tier: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub notes: Option<String>,
}

/// Root JSON artifact generated by `panadiga re index-symbols` and served by MCP/RAG.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct FirmwareSymbolIndex {
    pub schema_version: u32,
    pub firmware_train_id: String,
    pub module: String,
    pub sha256: String,
    pub base_va: String,
    pub size_bytes: usize,
    pub function_count: usize,
    pub destructive_function_count: usize,
    pub functions: Vec<FunctionSymbolEntry>,
}

/// Curated annotation overlay (name, span, ABI, side-effect classification) merged atop static discovery.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SymbolAnnotationOverlay {
    pub va: String,
    #[serde(default)]
    pub size_bytes: Option<u32>,
    #[serde(default)]
    pub name: Option<String>,
    #[serde(default)]
    pub abi: Option<String>,
    #[serde(default)]
    pub ret: Option<String>,
    #[serde(default)]
    pub side_effects: Option<SymbolSideEffect>,
    #[serde(default)]
    pub evidence_tier: Option<String>,
    #[serde(default)]
    pub notes: Option<String>,
}

/// Filter parameters for [`super::lookup_symbols`] and MCP `panadiga_symbol_lookup`.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct SymbolLookupQuery {
    pub train_id: Option<String>,
    pub module: Option<String>,
    pub va: Option<String>,
    pub name: Option<String>,
    pub caller_of: Option<String>,
    pub callee_of: Option<String>,
    pub side_effect: Option<SymbolSideEffect>,
    pub string_xref: Option<String>,
    pub mmio_xref: Option<String>,
    pub limit: Option<usize>,
}

/// Deterministic safety verdict emitted alongside lookup results.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SymbolLookupSafetyGate {
    pub blocked_for_unattended_call: bool,
    pub destructive_matches: usize,
    pub warning: Option<String>,
}

/// Matched symbol annotated with its owning `(firmware_train_id, module, base_va)`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SymbolLookupMatch {
    pub firmware_train_id: String,
    pub module: String,
    pub base_va: String,
    pub symbol: FunctionSymbolEntry,
}

/// Structured response returned by [`super::lookup_symbols`].
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SymbolLookupResponse {
    pub total_matches: usize,
    pub safety_gate: SymbolLookupSafetyGate,
    pub matches: Vec<SymbolLookupMatch>,
}
